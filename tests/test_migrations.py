"""Migration tests: the schema in code and the schema in migrations must agree.

The strong assertion here is ``alembic check``: it fails whenever a model changes
without a matching migration. That is the only way to keep an append-only
evidence store and a versioned task store from silently drifting apart.
"""

from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

import pytest
from alembic.config import Config
from sqlalchemy import create_engine

from alembic import command
from packages.core.metadata import (
    PLATFORM_METADATA,
    PLATFORM_TABLES,
    foreign_tables,
    registered_table_names,
)

ROOT = Path(__file__).resolve().parents[1]


def _config(url: str) -> Config:
    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT / "alembic"))
    cfg.set_main_option("sqlalchemy.url", url)
    return cfg


@pytest.fixture()
def migrated(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> tuple[str, Path]:
    db = tmp_path / "migrated.db"
    url = f"sqlite:///{db.as_posix()}"
    # env.py reads the env var first; the value must match the app's source of truth.
    monkeypatch.setenv("TRACEGUARD_DATABASE_URL", url)
    command.upgrade(_config(url), "head")
    return url, db


def _schema(path: Path) -> tuple[dict[str, tuple[Any, ...]], dict[str, list[str]]]:
    conn = sqlite3.connect(path)
    try:
        tables = [
            r[0]
            for r in conn.execute(
                "select name from sqlite_master where type='table' and name not like 'sqlite_%'"
            )
        ]
        cols = {
            t: tuple((r[1], (r[2] or "").upper()) for r in conn.execute(f"PRAGMA table_info({t})"))
            for t in tables
        }
        idx = {t: sorted(r[1] for r in conn.execute(f"PRAGMA index_list({t})")) for t in tables}
        return cols, idx
    finally:
        conn.close()


def test_declared_tables_are_all_registered() -> None:
    # R5-5.1 added the two durable-stream tables, so the owned set is 12.
    assert len(PLATFORM_TABLES) == 12
    assert set(PLATFORM_TABLES) <= registered_table_names()


def test_teamflow_tables_are_not_owned_by_the_platform_migration() -> None:
    """TeamFlow deploys separately; its tables must never enter this migration.

    TeamFlow's models are imported on purpose: without them ``foreign_tables()``
    is empty and the assertion below would be vacuous (it previously passed only
    because an unrelated table happened to be registered).
    """
    import apps.teamflow.eval_models  # noqa: F401 - registers eval_* tables
    import apps.teamflow.models  # noqa: F401 - registers tf_* tables

    foreign = foreign_tables()
    assert foreign, "expected TeamFlow tables to be registered on the shared base"
    assert all(name.startswith(("tf_", "eval_")) for name in foreign)
    assert not (set(PLATFORM_TABLES) & foreign)


def test_initial_migration_creates_every_platform_table(migrated: tuple[str, Path]) -> None:
    _, db = migrated
    cols, _ = _schema(db)
    assert set(cols) - {"alembic_version"} == set(PLATFORM_TABLES)


def test_migrated_schema_matches_the_models(migrated: tuple[str, Path], tmp_path: Path) -> None:
    _, db = migrated
    echo_db = tmp_path / "echo.db"
    engine = create_engine(f"sqlite:///{echo_db.as_posix()}")
    for meta in PLATFORM_METADATA:
        meta.create_all(engine)
    engine.dispose()

    migrated_cols, migrated_idx = _schema(db)
    model_cols, model_idx = _schema(echo_db)

    assert set(migrated_cols) - {"alembic_version"} == set(model_cols)
    for table in model_cols:
        # Compared as sets: an incremental migration appends a column with ALTER
        # TABLE, so physical order can differ from create_all while the schema is
        # functionally identical.
        assert set(migrated_cols[table]) == set(model_cols[table]), f"column drift in {table}"
        assert migrated_idx[table] == model_idx[table], f"index drift in {table}"


def test_alembic_check_detects_no_pending_model_changes(migrated: tuple[str, Path]) -> None:
    url, _ = migrated
    # Raises util.CommandError / AutogenerateDiffsDetected when the models drift.
    command.check(_config(url))


def test_downgrade_removes_all_platform_tables(migrated: tuple[str, Path]) -> None:
    url, db = migrated
    command.downgrade(_config(url), "base")
    cols, _ = _schema(db)
    assert set(cols) - {"alembic_version"} == set()


def test_upgrade_is_repeatable_after_downgrade(migrated: tuple[str, Path]) -> None:
    url, db = migrated
    command.downgrade(_config(url), "base")
    command.upgrade(_config(url), "head")
    cols, _ = _schema(db)
    assert set(cols) - {"alembic_version"} == set(PLATFORM_TABLES)


def test_every_table_has_a_primary_key(migrated: tuple[str, Path]) -> None:
    _, db = migrated
    conn = sqlite3.connect(db)
    try:
        for table in PLATFORM_TABLES:
            info = list(conn.execute(f"PRAGMA table_info({table})"))
            assert any(row[5] == 1 for row in info), f"{table} has no primary key"
    finally:
        conn.close()


def test_reference_columns_are_indexed(migrated: tuple[str, Path]) -> None:
    """Lookups by run/task/edge endpoint are the hot path; they must not full-scan."""
    _, db = migrated
    conn = sqlite3.connect(db)
    try:
        # ev_event stores run_id inside context_refs (JSON), so the indexed
        # column to check there is producer_instance_id.
        expectations = {
            "tg_run": "task_id",
            "tg_step": "run_id",
            "evd_record": "run_id",
            "ev_event": "producer_instance_id",
            "gr_edge": "src",
        }
        for table, column in expectations.items():
            # PRAGMA index_list columns: seq, name, unique, origin, partial
            indexed = {row[1] for row in conn.execute(f"PRAGMA index_list({table})")}
            cols_in_indexes = set()
            for name in indexed:
                cols_in_indexes |= {r[2] for r in conn.execute(f"PRAGMA index_info({name})")}
            assert column in cols_in_indexes, f"{table}.{column} is not indexed"
    finally:
        conn.close()


def test_postgresql_ddl_renders_offline(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """-sql mode proves the migration compiles for PostgreSQL's dialect.

    This is a DDL-compilation check, NOT a live PostgreSQL verification: no
    server was contacted. Phase-12 style claims about PG would need a running
    instance and are therefore NOT made anywhere.
    """
    pytest.importorskip("psycopg", reason="psycopg driver not installed")
    url = "postgresql+psycopg://tg:tg@localhost:5432/traceguard"
    monkeypatch.setenv("TRACEGUARD_DATABASE_URL", url)
    command.upgrade(_config(url), "head", sql=True)
    rendered = capsys.readouterr().out
    for table in PLATFORM_TABLES:
        assert f"CREATE TABLE {table}" in rendered, f"{table} missing from PG DDL"
    assert "BEGIN;" in rendered and "COMMIT;" in rendered
