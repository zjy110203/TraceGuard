# -------------------------------------------------------- invalid + semantic


def _mutators(sample: dict[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    """Candidate structural breakages, tried in order until one really fails."""
    out: list[tuple[str, dict[str, Any]]] = []
    keys = list(sample)
    if keys:
        first = keys[0]
        dropped = dict(sample)
        dropped.pop(first, None)
        out.append((f"missing_{first}", dropped))
    str_key = next((k for k, v in sample.items() if isinstance(v, str)), None)
    if str_key:
        wrong = dict(sample)
        wrong[str_key] = 12345
        out.append((f"wrong_type_{str_key}", wrong))
    added = dict(sample)
    added["unexpected_field"] = 1
    out.append(("extra_field", added))
    return out


def _semantic_samples(valid: dict[str, dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """Instances that are structurally fine but violate a cross-field rule."""
    out: dict[str, dict[str, Any]] = {}

    intent = _jsonable(valid["C01"]["intent.json"])
    blank_id = json.loads(json.dumps(intent))
    blank_id["intent_id"] = ""
    out["C01"] = {"blank_intent_id.json": blank_id}

    case = _jsonable(next(iter(valid["C02"].values())))
    broken = json.loads(json.dumps(case))
    broken["oracle_bindings"] = broken["oracle_bindings"][1:]
    out["C02"] = {"oracle_binding_missing.json": broken}

    binding = _jsonable(next(iter(valid["C03"].values())))
    dup = json.loads(json.dumps(binding))
    dup["supporting"] = [dict(dup["primary"])]
    out["C03"] = {"supporting_duplicates_primary.json": dup}

    report = _jsonable(valid["C04"]["run_report.json"])
    no_finish = json.loads(json.dumps(report))
    no_finish["finished_at"] = ""
    out["C04"] = {"terminal_without_finished_at.json": no_finish}

    event = _jsonable(valid["C05"]["event.json"])
    time_travel = json.loads(json.dumps(event))
    time_travel["recorded_at"] = "2026-11-22T03:59:59+00:00"
    out["C05"] = {"recorded_before_occurred.json": time_travel}

    raw = _jsonable(valid["C06"]["raw_evidence.json"])
    raw_with_parents = json.loads(json.dumps(raw))
    raw_with_parents["derived_from"] = ["evd_0000"]
    out["C06"] = {"raw_with_parents.json": raw_with_parents}

    edge = _jsonable(valid["C07"]["edge.json"])
    causal = json.loads(json.dumps(edge))
    causal["relation"] = "direct_causal"
    causal["basis_fields"] = ""
    out["C07"] = {"causal_without_basis.json": causal}

    diag = _jsonable(valid["C08"]["diagnosis.json"])
    no_rule = json.loads(json.dumps(diag))
    no_rule["hypotheses"][0]["confirmation_rule"] = ""
    out["C08"] = {"confirmed_without_rule.json": no_rule}

    spec = _jsonable(valid["C09"]["spec.json"])
    writer = json.loads(json.dumps(spec))
    writer["read_only"] = False
    writer["side_effects"] = ""
    out["C09"] = {"non_readonly_without_side_effects.json": writer}

    disp = json.loads(json.dumps(valid["C10"]["disposition.json"]))
    disp["diagnosis_status"] = "CONFIRMED"
    disp["disposition"] = "NEEDS_MORE_EVIDENCE"
    out["C10"] = {"confirmed_routed_to_more_evidence.json": disp}

    proposal = _jsonable(valid["C11"]["proposal.json"])
    forbidden = json.loads(json.dumps(proposal))
    forbidden["change_kinds"] = ["oracle_change"]
    out["C11"] = {"forbidden_oracle_change.json": forbidden}

    exp = _jsonable(valid["C12"]["experiment.json"])
    not_run = json.loads(json.dumps(exp))
    not_run["status"] = "NOT_RUN"
    not_run["metrics"] = {"macro_f1": 0.99}
    out["C12"] = {"not_run_with_metrics.json": not_run}
    return out


# ------------------------------------------------------------------------ main


def main() -> None:
    schemas = build_all_schemas()
    valid = _valid_samples()
    semantic = _semantic_samples(valid)

    for cid, schema in schemas.items():
        _write(SCHEMA_DIR / f"{cid}_{schema['title'].replace(' ', '_')}.schema.json", schema)

    # Valid samples (must pass both stages).
    for cid, files in valid.items():
        for name, obj in files.items():
            _write(SAMPLE_DIR / cid / "valid" / name, _jsonable(obj))

    # Semantic samples (structure OK, semantics bad).
    for cid, files in semantic.items():
        for name, payload in files.items():
            _write(SAMPLE_DIR / cid / "semantic" / name, payload)

    # Invalid samples: generate, then verify they actually fail.
    from jsonschema import Draft202012Validator

    written: dict[str, list[str]] = {}
    for cid, files in valid.items():
        for name, obj in files.items():
            sample = _jsonable(obj)
            validator = Draft202012Validator(schemas[cid])
            picked: tuple[str, dict[str, Any]] | None = None
            for label, candidate in _mutators(sample):
                if not validator.is_valid(candidate):
                    picked = (label, candidate)
                    break
            if picked is None:
                raise SystemExit(f"[{cid}/{name}] could not construct a failing sample")
            label, payload = picked
            target = SAMPLE_DIR / cid / "invalid" / f"{Path(name).stem}__{label}.json"
            _write(target, payload)
            written.setdefault(cid, []).append(target.name)

    # Registry manifest.
    contracts = []
    for cid, schema in schemas.items():
        rel_schema = next(SCHEMA_DIR.glob(f"{cid}_*.schema.json")).name
        contracts.append(
            {
                "id": cid,
                "name": schema["title"],
                "version": "0.2.0-draft",
                "status": "draft",
                "owner_role": "待分配",
                "schema_file": rel_schema,
                "valid_samples": sorted(
                    p.name for p in (SAMPLE_DIR / cid / "valid").glob("*.json")
                ),
                "invalid_samples": sorted(written.get(cid, [])),
                "semantic_samples": sorted(
                    p.name for p in (SAMPLE_DIR / cid / "semantic").glob("*.json")
                ),
                "semantic_rule_count": len(SEMANTIC_RULES.get(cid, ())),
            }
        )

    manifest = {
        "baseline": "v1.1",
        "generated_by": "scripts.build_contracts",
        "note": (
            "Schema 由真实 dataclass 生成（packages/contracts/schema_gen.py）；"
            "status=draft 表示未经人工冻结，不得当作已批准契约。"
            "语义规则见 packages/contracts/semantic.py 的 SEMANTIC_RULES。"
        ),
        "contracts": contracts,
    }
    _write(REGISTRY, manifest)

    registry = ContractRegistry.load()
    summary = []
    for cid in registry.contract_ids():
        e = registry.entry(cid)
        summary.append(
            f"  {cid:4} {e['name']:15} rules={e['semantic_rule_count']:2} "
            f"valid={len(e['valid_samples'])} invalid={len(e['invalid_samples'])} "
            f"semantic={len(e['semantic_samples'])}"
        )
    print("contracts generated:")
    print("\n".join(summary))
    total_rules = sum(e["semantic_rule_count"] for e in contracts)
    print(f"total semantic rules: {total_rules}")
    print(f"schemas: {len(schemas)}  missing: {registry.missing_schemas() or 'none'}")


if __name__ == "__main__":
    main()
